"""## Cell 7 — Shared Training Loop Utilities"""

import time
import torch
import torch.nn as nn

def train_one_epoch(model, loader, criterion, optimizer, device, scaler):
    model.train()
    running_loss, correct, total = 0.0, 0, 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        with torch.cuda.amp.autocast(enabled=(device.type == 'cuda')):
            outputs = model(imgs)
            loss    = criterion(outputs, labels)
        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        scaler.step(optimizer)
        scaler.update()
        running_loss += loss.item() * imgs.size(0)
        correct += (outputs.argmax(1) == labels).sum().item()
        total   += imgs.size(0)
    return running_loss / total, correct / total

@torch.no_grad()
def evaluate(model, loader, criterion, device):
    model.eval()
    running_loss, correct, total = 0.0, 0, 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        with torch.cuda.amp.autocast(enabled=(device.type == 'cuda')):
            outputs = model(imgs)
            loss    = criterion(outputs, labels)
        running_loss += loss.item() * imgs.size(0)
        correct += (outputs.argmax(1) == labels).sum().item()
        total   += imgs.size(0)
    return running_loss / total, correct / total

def run_training_loop(model, train_loader, val_loader, criterion, optimizer,
                      scheduler, scaler, epochs, device, save_path,
                      best_val_acc, label):
    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f'\n{chr(9472)*55}')
    print(f'  {label}')
    print(f'  Trainable params: {trainable:,}')
    print(f'{chr(9472)*55}')
    print(f'{"Epoch":>6}  {"Tr Loss":>8}  {"Tr Acc":>7}  {"Vl Loss":>8}  {"Vl Acc":>7}  {"Time":>6}')
    print('-' * 55)
    for epoch in range(1, epochs + 1):
        t0 = time.time()
        tr_loss, tr_acc = train_one_epoch(model, train_loader, criterion, optimizer, device, scaler)
        vl_loss, vl_acc = evaluate(model, val_loader, criterion, device)
        scheduler.step()
        elapsed = time.time() - t0
        print(f'{epoch:>6}  {tr_loss:>8.4f}  {tr_acc:>6.2%}  {vl_loss:>8.4f}  {vl_acc:>6.2%}  {elapsed:>5.1f}s')
        if vl_acc > best_val_acc:
            best_val_acc = vl_acc
            torch.save({'epoch': epoch, 'model_state': model.state_dict(),
                        'val_acc': vl_acc}, save_path)
            print(f'         ^ Best saved ({vl_acc:.2%})')
    return best_val_acc

