"""## Cell 10 — Train Model B: MobileNetV3 (Transfer Learning)
Two-phase: warm-up head (10 epochs) then full fine-tune (30 epochs).  
Expect **92-96% accuracy**.
"""

import torch.optim as optim
from torch.optim.lr_scheduler import CosineAnnealingLR
from pathlib import Path

HEAD_EPOCHS   = 5
FT_EPOCHS     = 30
LR_HEAD       = 1e-3
LR_FT         = 1e-4

Path('models').mkdir(exist_ok=True)
transfer_save = Path('models/transfer_best.pth')
criterion_tr  = nn.CrossEntropyLoss(label_smoothing=0.1)
scaler_tr     = torch.cuda.amp.GradScaler(enabled=(DEVICE.type == 'cuda'))

# Phase 1: frozen backbone
transfer_model = build_transfer_model(NUM_CLASSES, freeze_backbone=True).to(DEVICE)
opt_head  = optim.AdamW(filter(lambda p: p.requires_grad, transfer_model.parameters()),
                         lr=LR_HEAD, weight_decay=1e-4)
sched_head = CosineAnnealingLR(opt_head, T_max=HEAD_EPOCHS, eta_min=1e-6)

best_transfer = run_training_loop(
    transfer_model, train_loader, val_loader, criterion_tr,
    opt_head, sched_head, scaler_tr,
    HEAD_EPOCHS, DEVICE, transfer_save, 0.0,
    'Phase 1 - Head warm-up (backbone frozen)'
)

# Phase 2: full fine-tune with differential LRs
unfreeze_all(transfer_model)
backbone_params = [p for n, p in transfer_model.named_parameters() if 'classifier' not in n]
head_params     = [p for n, p in transfer_model.named_parameters() if 'classifier'     in n]
opt_ft   = optim.AdamW([
    {'params': backbone_params, 'lr': LR_FT * 0.1},
    {'params': head_params,     'lr': LR_FT},
], weight_decay=1e-4)
sched_ft = CosineAnnealingLR(opt_ft, T_max=FT_EPOCHS, eta_min=1e-7)

best_transfer = run_training_loop(
    transfer_model, train_loader, val_loader, criterion_tr,
    opt_ft, sched_ft, scaler_tr,
    FT_EPOCHS, DEVICE, transfer_save, best_transfer,
    'Phase 2 - Full fine-tuning (backbone unfrozen)'
)

# Save class_to_idx into checkpoint
ckpt = torch.load(transfer_save)
ckpt['class_to_idx'] = class_to_idx
torch.save(ckpt, transfer_save)

transfer_model.load_state_dict(ckpt['model_state'])
